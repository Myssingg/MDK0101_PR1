CREATE TABLE users (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "fullName"  varchar(150) NOT NULL,
    "login"     varchar(50)  NOT NULL,
    "password"  varchar(100) NOT NULL,
    "phone"     varchar(20)  NOT NULL,
    "street"    varchar(150) NOT NULL,
    "house"     varchar(20)  NOT NULL,
    "apartment" integer,
    CONSTRAINT "usersLoginUnique" UNIQUE ("login"),
    CONSTRAINT "usersPhoneFormat"
        CHECK ("phone" ~ '^\+7 [0-9]{3} [0-9]{3}-[0-9]{2}-[0-9]{2}$'),
    CONSTRAINT "usersApartmentPositive"
        CHECK ("apartment" IS NULL OR "apartment" > 0)
);

CREATE TABLE bouquets (
    id           integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"       varchar(200)  NOT NULL,
    "imagePath"  varchar(200)  NOT NULL,
    "price"      numeric(10,2) NOT NULL,
    CONSTRAINT "bouquetsPricePositive" CHECK ("price" > 0)
);

CREATE TABLE baskets (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId"     integer NOT NULL REFERENCES users(id)    ON DELETE CASCADE,
    "bouquetId"  integer NOT NULL REFERENCES bouquets(id) ON DELETE RESTRICT,
    "quantity"   integer NOT NULL DEFAULT 1,
    CONSTRAINT "basketsQuantityPositive" CHECK ("quantity" > 0),
    CONSTRAINT "basketsUserBouquetUnique" UNIQUE ("userId", "bouquetId")
);

CREATE TABLE orders (
    id                   integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userId"             integer       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    "createdAt"          timestamp     NOT NULL DEFAULT now(),
    "deliveryTime"       timestamp     NOT NULL,
    "deliveryStreet"     varchar(150)  NOT NULL,
    "deliveryHouse"      varchar(20)   NOT NULL,
    "deliveryApartment"  integer,
    "totalCost"          numeric(10,2) NOT NULL,
    CONSTRAINT "ordersTotalCostPositive" CHECK ("totalCost" >= 0),
    CONSTRAINT "ordersDeliveryApartmentPositive"
        CHECK ("deliveryApartment" IS NULL OR "deliveryApartment" > 0)
);

CREATE TABLE "orderItems" (
    id           integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "orderId"    integer       NOT NULL REFERENCES orders(id)   ON DELETE CASCADE,
    "bouquetId"  integer       NOT NULL REFERENCES bouquets(id) ON DELETE RESTRICT,
    "quantity"   integer       NOT NULL,
    "unitPrice"  numeric(10,2) NOT NULL,
    CONSTRAINT "orderItemsQuantityPositive" CHECK ("quantity" > 0),
    CONSTRAINT "orderItemsUnitPricePositive" CHECK ("unitPrice" >= 0),
    CONSTRAINT "orderItemsOrderBouquetUnique" UNIQUE ("orderId", "bouquetId")
);

CREATE INDEX "ordersUserIdIdx"   ON orders ("userId");
